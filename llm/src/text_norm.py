# 否定词。命中位置前 3 个字符内出现这些词，视为该命中被否定。
NEGATIONS = ("不要", "不想", "别", "勿", "避免", "除了", "不是", "无需", "不用",
             "不考虑", "没有")

_PUNCT = re.compile(r"[\s，。,.!?！？、；;：:（）()\[\]【】\"'“”‘’《》<>/\\|~`"
                    r"@#$%^&*_+=-]+")


def to_simplified(text: str) -> str:
    return "".join(_TRAD.get(ch, ch) for ch in (text or ""))


def normalize(text: str) -> str:
    """归一化为可做子串匹配的形式（小写、无标点、无语气词）。"""
    s = unicodedata.normalize("NFKC", text or "").lower()
    s = to_simplified(s)
    for src, dst in _UNIT:
        s = s.replace(src, dst)
    s = _PUNCT.sub("", s)
    for filler in _FILLER:
        s = s.replace(filler, "")
    return s


def expand(text: str) -> str:
    """归一化后追加同义词的规范说法，供关键词匹配使用。"""
    base = normalize(text)
    extra = []
    for src, dst in SYNONYMS.items():
        key = normalize(src)
        if key and key in base and dst not in base:
            extra.append(dst)
    return base + "".join(dict.fromkeys(extra))


def negated(text: str, index: int, width: int = 3) -> bool:
    """归一化文本中 index 处的命中是否处于否定语境。"""
    head = text[max(0, index - width):index]
    return any(neg in head for neg in NEGATIONS)
